export function flower(x,y,fill=colors.pink) {
  return rect(x+6,y+9,3,13,colors.green)+pixels(['00100','01110','11111','01110','00100'],x,y,3,fill)+rect(x+6,y+6,3,3,colors.gold);
}
export function meadow(x,y,w,h) {
  let svg=rect(x,y,w,h,colors.grass)+rect(x,y,w,6,colors.mint);
  for(let dx=8;dx<w-12;dx+=24) svg+=rect(x+dx,y+12,8,4,'#569b79');
  if(h>=34) for(let dx=14;dx<w-12;dx+=40) svg+=rect(x+dx,y+30,4,4,'#94cea2');
  return svg;
}
