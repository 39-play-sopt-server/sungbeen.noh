export const escape = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&apos;'}[c]));
export const rect=(x,y,w,h,fill)=>`<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${fill}"/>`;
export const text=(x,y,value,size=14,color=colors.ink,extra='')=>`<text x="${x}" y="${y}" font-size="${size}" fill="${color}" ${extra}>${escape(value)}</text>`;
export function panel(x,y,w,h,fill,edge=colors.ink) {
  return rect(x+6,y+6,w,h,edge)+rect(x,y,w,h,edge)+rect(x+4,y+4,w-8,h-8,fill);
}
