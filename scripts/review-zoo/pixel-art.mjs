export function pixels(rows,x,y,scale,fill) {
  return `<g transform="translate(${x} ${y}) scale(${scale})" shape-rendering="crispEdges">${rows.map((row,py)=>[...row].map((p,px)=>p==='1'?rect(px,py,1,1,fill):'').join('')).join('')}</g>`;
}
export function pixelText(value,x,y,scale=3,fill=colors.ink) {
  return `<g aria-label="${escape(value)}">${[...value.toUpperCase()].map((c,i)=>pixels(glyphs[c]??glyphs['?'],x+i*6*scale,y,scale,fill)).join('')}</g>`;
}
export function creature(pixels,x,y,scale=5,animate=false) {
  const art=`<g transform="translate(${x} ${y}) scale(${scale})" shape-rendering="crispEdges">${pixels.map(([px,py,color,opacity])=>`<rect x="${px}" y="${py}" width="1" height="1" fill="${color}" opacity="${opacity}"/>`).join('')}</g>`;
  return animate?`<g class="hop">${art}</g>`:art;
}
